export const DICT: Record<Lang, Record<Key, string>> = { ar, en };

export type TFn = (k: Key, vars?: Record<string, string | number>) => string;
export const makeT = (lang: Lang): TFn => (k, vars) =>
  DICT[lang][k].replace(/\{(\w+)\}/g, (_, name) => String(vars?.[name] ?? ""));

// جمع الأسماء المعدودة: العربية (واحد / اثنان / 3–10 جمع / 11+ مفرد منصوب) والإنجليزية (مفرد / جمع).
export type Noun = "hour" | "day" | "patient";
const AR_NOUN: Record<Noun, { one: string; two: string; twoNom: string; few: string; many: string }> = {
  hour: { one: "ساعة واحدة", two: "ساعتين", twoNom: "ساعتان", few: "ساعات", many: "ساعة" },
  day: { one: "يوم واحد", two: "يومين", twoNom: "يومان", few: "أيام", many: "يوماً" },
  patient: { one: "مريض واحد", two: "مريضين", twoNom: "مريضان", few: "مرضى", many: "مريضاً" },
};
const EN_NOUN: Record<Noun, [string, string]> = { hour: ["hour", "hours"], day: ["day", "days"], patient: ["patient", "patients"] };

export const makeNt = (lang: Lang) => (noun: Noun, n: number, o: { text?: string; nom?: boolean } = {}): string => {
  const shown = o.text ?? n.toLocaleString("en-US");
  if (lang === "en") return `${shown} ${EN_NOUN[noun][n === 1 ? 0 : 1]}`;
  const f = AR_NOUN[noun];
  if (!Number.isInteger(n)) return `${shown} ${f.many}`;
  if (n === 1) return f.one;
  if (n === 2) return o.nom ? f.twoNom : f.two;
  return `${shown} ${n <= 10 ? f.few : f.many}`;
};
export type NtFn = ReturnType<typeof makeNt>;

export const I18nContext = createContext<{ lang: Lang; t: TFn; nt: NtFn }>({ lang: "ar", t: makeT("ar"), nt: makeNt("ar") });
export const useI18n = () => useContext(I18nContext);
